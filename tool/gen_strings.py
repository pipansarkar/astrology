"""Writes lib/l10n/strings_bn.dart and strings_hi.dart from
tool/translations_bn.py and tool/translations_hi.py.

  python3 -I tool/gen_strings.py

Fails if a translation drops or adds a {placeholder}.
"""
import re
import sys
from pathlib import Path

TOOL = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOL))
from translations_bn import BN  # noqa: E402
from translations_hi import HI  # noqa: E402

ROOT = TOOL.parent


def dart(s):
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n")
    return f"'{s}'"


errors = []
for lang, table in (("bn", BN), ("hi", HI)):
    for en, tr in table.items():
        if set(re.findall(r"\{\w+\}", en)) != set(re.findall(r"\{\w+\}", tr)):
            errors.append(f"{lang}: placeholder mismatch in {en!r}")
    lines = [
        f"// {'Bengali' if lang == 'bn' else 'Hindi'} UI strings, keyed by the English text.",
        "// Generated by tool/gen_strings.py from tool/translations_" + lang + ".py. Do not edit.",
        "",
        f"const strings{lang.capitalize()} = <String, String>{{",
    ]
    for en in sorted(table):
        lines.append(f"  {dart(en)}:\n      {dart(table[en])},")
    lines.append("};")
    (ROOT / f"lib/l10n/strings_{lang}.dart").write_text("\n".join(lines) + "\n")

if errors:
    print("\n".join(errors))
    sys.exit(1)
print(f"bn: {len(BN)} strings, hi: {len(HI)} strings")
