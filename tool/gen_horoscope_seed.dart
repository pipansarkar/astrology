// Generates the Supabase migration that creates and seeds `horoscope_texts`
// from lib/horoscope/default_texts.dart.
//
//   dart run tool/gen_horoscope_seed.dart > supabase/migrations/20261105000100_horoscope_texts.sql

import 'package:astrology/horoscope/default_texts.dart';

String q(String s) => "'${s.replaceAll("'", "''")}'";

void main(List<String> args) {
  if (args.contains('--translations')) {
    final rows = <String>[
      for (final (lang, g, t) in [
        ('bn', defaultGocharBn, defaultTaraBn),
        ('hi', defaultGocharHi, defaultTaraHi),
      ]) ...[
        for (var i = 0; i < g.length; i++)
          "  ('gochar', ${i + 1}, '$lang', ${q(g[i].title)}, ${q(g[i].body)})",
        for (var i = 0; i < t.length; i++)
          "  ('tara', ${i + 1}, '$lang', ${q(t[i].title)}, ${q(t[i].body)})",
      ],
    ];
    // ignore: avoid_print
    print(
      '-- Bengali and Hindi horoscope texts.\n'
      '-- Generated by tool/gen_horoscope_seed.dart --translations.\n\n'
      'insert into public.horoscope_texts (kind, key, lang, title, body) values\n'
      '${rows.join(',\n')}\n'
      'on conflict (kind, key, lang) do nothing;',
    );
    return;
  }
  final out = StringBuffer('''
-- Daily horoscope texts. Public read; edit rows in the Supabase dashboard
-- (Table Editor) to change wording or add languages (lang = 'bn', 'hi').
-- Generated by tool/gen_horoscope_seed.dart.

create table public.horoscope_texts (
  kind       text not null check (kind in ('gochar', 'tara')),
  key        smallint not null check (key between 1 and 12),
  lang       text not null default 'en',
  title      text not null,
  body       text not null,
  updated_at timestamptz not null default now(),
  primary key (kind, key, lang)
);

alter table public.horoscope_texts enable row level security;

create policy "Anyone can read horoscope texts"
  on public.horoscope_texts for select
  to anon, authenticated
  using (true);

insert into public.horoscope_texts (kind, key, lang, title, body) values
''');
  final rows = <String>[
    for (var i = 0; i < defaultGochar.length; i++)
      "  ('gochar', ${i + 1}, 'en', ${q(defaultGochar[i].title)}, ${q(defaultGochar[i].body)})",
    for (var i = 0; i < defaultTara.length; i++)
      "  ('tara', ${i + 1}, 'en', ${q(defaultTara[i].title)}, ${q(defaultTara[i].body)})",
  ];
  out
    ..write(rows.join(',\n'))
    ..writeln(';');
  // ignore: avoid_print
  print(out);
}
